#!/usr/bin/env node
// Builds js/ios-unlock-src.js (TDC.IOS_BOOKMARKLET) from connector/ios-unlock-bookmarklet.js: minify with terser
// (ES2018 output, no outside scripts), then make it a javascript: URL. "%" and "#" are percent-encoded because the
// browser percent-decodes a bookmarklet once before running it; nothing else is encoded so it stays short.
// Usage: NODE_PATH=<dir with terser> node tools/build-bookmarklet.js      (prints the size)
const fs = require("fs"), path = require("path"), root = path.join(__dirname, "..");
const { minify } = require("terser");
(async () => {
  const src = fs.readFileSync(path.join(root, "connector/ios-unlock-bookmarklet.js"), "utf8");
  const out = await minify(src, { ecma: 2018, compress: { passes: 2 }, mangle: { toplevel: true }, format: { ascii_only: true, comments: false } });
  const code = out.code.replace(/;$/, "");
  const url = "javascript:" + code.replace(/%/g, "%25").replace(/#/g, "%23").replace(/\n/g, " ");
  fs.writeFileSync(path.join(root, "js/ios-unlock-src.js"),
    "/* ios-unlock-src.js — GENERATED by tools/build-bookmarklet.js from connector/ios-unlock-bookmarklet.js. Do not edit. */\n" +
    "window.TDC = window.TDC || {};\nwindow.TDC.IOS_BOOKMARKLET = " + JSON.stringify(url) + ";\n");
  console.log("wrote js/ios-unlock-src.js: bookmarklet " + url.length + " chars (" + Buffer.byteLength(url) + " bytes)");
})().catch((e) => { console.error(e); process.exit(1); });
